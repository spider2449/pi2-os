//! A/B system updates: root filesystem plus kernel.
//!
//! Each slot is a root partition (p2/p3) and a directory of the same name on
//! the boot partition (`p2/`, `p3/`) holding that slot's kernel, device tree
//! and command line. The firmware picks the directory through `os_prefix`.
//!
//! An update is written to the inactive slot and booted exactly once through
//! the firmware's one-shot `tryboot` flag, which makes the firmware read
//! `tryboot.txt` instead of `config.txt` for that boot only. The new system
//! commits itself (makes `config.txt` point at its slot) once the engine is
//! ready. Any failure before that, including a kernel panic, ends in a normal
//! reboot, and the firmware then boots the old slot again.
//!
//! GPU firmware (bootcode.bin, start_cd.elf, fixup_cd.dat) is shared: a hang
//! inside the firmware happens before anything could roll back, so firmware
//! is only replaced on request, after the new slot has committed.

/// Kernel command line marker of a trial boot.
pub const TRIAL_FLAG: &str = "pios.try=1";
/// Partition numbers of the two root slots (see board/rpi2/genimage.cfg).
pub const SLOTS: [u32; 2] = [2, 3];
pub const CONFIG: &str = "config.txt";
pub const CMDLINE: &str = "cmdline.txt";
pub const TRY_CMDLINE: &str = "cmdline.try.txt";
pub const TRY_CONFIG: &str = "tryboot.txt";
/// Per-slot description of what was installed (see `Manifest`).
pub const MANIFEST: &str = "manifest.txt";
/// Firmware staged inside a slot directory, installed when the slot commits.
pub const STAGED_FIRMWARE: &str = "firmware";
/// Files the firmware loads relative to `os_prefix`.
pub const KERNEL_FILES: [&str; 2] = ["kernel7.img", "bcm2709-rpi-2-b.dtb"];
/// Shared GPU firmware files an update may replace.
pub const FIRMWARE_FILES: [&str; 3] = ["bootcode.bin", "start_cd.elf", "fixup_cd.dat"];
/// Name of the root filesystem inside an update bundle.
pub const BUNDLE_ROOTFS: &str = "rootfs.squashfs";
/// squashfs superblock magic ("hsqs"), checked before overwriting a slot.
pub const SQUASHFS_MAGIC: &[u8; 4] = b"hsqs";
/// Marker of the block pios-update owns at the end of config.txt/tryboot.txt.
const MANAGED: &str = "# Generated by pios-update";

/// Value of `root=` in a kernel command line.
pub fn root_of(cmdline: &str) -> Option<&str> {
    cmdline.split_whitespace().find_map(|a| a.strip_prefix("root="))
}

/// Replace (or add) `root=` and drop the trial flag.
pub fn with_root(cmdline: &str, root: &str) -> String {
    let mut found = false;
    let mut args: Vec<String> = cmdline
        .split_whitespace()
        .filter(|a| *a != TRIAL_FLAG)
        .map(|a| {
            if a.starts_with("root=") {
                found = true;
                format!("root={root}")
            } else {
                a.to_string()
            }
        })
        .collect();
    if !found {
        args.push(format!("root={root}"));
    }
    args.join(" ")
}

/// Command line for the trial boot of `root`.
pub fn trial_cmdline(cmdline: &str, root: &str) -> String {
    format!("{} {TRIAL_FLAG}", with_root(cmdline, root))
}

pub fn is_trial(cmdline: &str) -> bool {
    cmdline.split_whitespace().any(|a| a == TRIAL_FLAG)
}

fn split_partition(dev: &str) -> Option<(&str, u32)> {
    let digits = dev.len() - dev.trim_end_matches(|c: char| c.is_ascii_digit()).len();
    let (base, num) = dev.split_at(dev.len() - digits);
    Some((base, num.parse().ok()?))
}

/// The other root slot's device, e.g. /dev/mmcblk0p2 -> /dev/mmcblk0p3.
pub fn other_root(active: &str) -> Option<String> {
    let (base, num) = split_partition(active)?;
    let other = match SLOTS {
        [a, b] if num == a => b,
        [a, b] if num == b => a,
        _ => return None,
    };
    Some(format!("{base}{other}"))
}

/// Boot partition directory of a root slot: /dev/mmcblk0p3 -> "p3".
pub fn slot_dir(root: &str) -> Option<String> {
    let (_, num) = split_partition(root)?;
    SLOTS.contains(&num).then(|| format!("p{num}"))
}

/// The user's part of config.txt: everything before the managed block.
pub fn base_config(config_txt: &str) -> &str {
    match config_txt.find(MANAGED) {
        Some(i) => config_txt[..i].trim_end(),
        None => config_txt.trim_end(),
    }
}

/// config.txt (or tryboot.txt with `trial`) that boots the kernel from slot
/// directory `dir`. Without `dir` (a board still on the flat layout) only the
/// trial command line is selected. `[all]` resets any conditional section
/// the user's config may end with.
///
/// The firmware ignores `os_prefix` unless the kernel and device tree exist
/// under it, so a missing slot directory falls back to the flat layout.
pub fn slot_config(config_txt: &str, dir: Option<&str>, trial: bool) -> String {
    let mut s = base_config(config_txt).to_string();
    let what = if trial { "one-shot trial boot" } else { "boot slot" };
    s.push_str(&format!("\n\n{MANAGED}: {what}. Do not edit below.\n[all]\n"));
    if let Some(d) = dir {
        s.push_str(&format!("os_prefix={d}/\n"));
    }
    if trial {
        s.push_str(&format!("cmdline={TRY_CMDLINE}\n"));
    }
    s
}

/// Slot directory selected by a config.txt, if any.
pub fn configured_slot(config_txt: &str) -> Option<&str> {
    config_txt
        .lines()
        .rev()
        .find_map(|l| l.trim().strip_prefix("os_prefix="))
        .map(|p| p.trim_end_matches('/'))
}

/// Lowercase hex encoding.
pub fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// `manifest.txt` of an update bundle and of an installed slot:
///
/// ```text
/// version 0.1.0 2026-10-31 a9746de
/// <sha256>  kernel7.img
/// <sha256>  rootfs.squashfs
/// ```
#[derive(Debug, Default, Clone, PartialEq)]
pub struct Manifest {
    pub version: String,
    /// (file name, sha256 hex), in file order.
    pub files: Vec<(String, String)>,
}

impl Manifest {
    pub fn parse(text: &str) -> Result<Self, String> {
        let mut m = Manifest::default();
        for line in text.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')) {
            if let Some(v) = line.strip_prefix("version ") {
                m.version = v.trim().to_string();
                continue;
            }
            let (sum, name) = line.split_once(char::is_whitespace).ok_or_else(|| format!("bad manifest line: {line}"))?;
            let name = name.trim();
            if sum.len() != 64 || !sum.bytes().all(|b| b.is_ascii_hexdigit()) {
                return Err(format!("bad sha256 for {name}"));
            }
            if name.is_empty() || name.contains('/') || name.starts_with('.') {
                return Err(format!("bad file name in manifest: {name:?}"));
            }
            m.files.push((name.to_string(), sum.to_ascii_lowercase()));
        }
        Ok(m)
    }

    pub fn sha256(&self, name: &str) -> Option<&str> {
        self.files.iter().find(|(n, _)| n == name).map(|(_, s)| s.as_str())
    }

    pub fn render(&self) -> String {
        let mut s = format!("version {}\n", self.version);
        for (name, sum) in &self.files {
            s.push_str(&format!("{sum}  {name}\n"));
        }
        s
    }
}

/// Where a bundle member goes, from its file name.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Member {
    Rootfs,
    Kernel,
    Firmware,
}

pub fn classify(name: &str) -> Option<Member> {
    if name == BUNDLE_ROOTFS {
        Some(Member::Rootfs)
    } else if KERNEL_FILES.contains(&name) {
        Some(Member::Kernel)
    } else if FIRMWARE_FILES.contains(&name) {
        Some(Member::Firmware)
    } else {
        None
    }
}

