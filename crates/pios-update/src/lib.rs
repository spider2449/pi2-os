#[cfg(test)]
mod tests {
    use super::*;

    const CMD: &str = "console=tty1 root=/dev/mmcblk0p2 rootfstype=squashfs ro rootwait panic=5";

    #[test]
    fn switches_root_and_marks_trial() {
        let t = trial_cmdline(CMD, "/dev/mmcblk0p3");
        assert_eq!(root_of(&t), Some("/dev/mmcblk0p3"));
        assert!(is_trial(&t));
        assert!(t.contains("rootfstype=squashfs") && t.contains("panic=5"));
        // Committing drops the flag again.
        let committed = with_root(&t, "/dev/mmcblk0p3");
        assert!(!is_trial(&committed));
        assert_eq!(committed.split_whitespace().filter(|a| a.starts_with("root=")).count(), 1);
    }

    #[test]
    fn finds_other_slot_and_its_directory() {
        assert_eq!(other_root("/dev/mmcblk0p2").as_deref(), Some("/dev/mmcblk0p3"));
        assert_eq!(other_root("/dev/mmcblk0p3").as_deref(), Some("/dev/mmcblk0p2"));
        assert_eq!(other_root("/dev/mmcblk0p4"), None);
        assert_eq!(other_root("/dev/root"), None);
        assert_eq!(slot_dir("/dev/mmcblk0p3").as_deref(), Some("p3"));
        assert_eq!(slot_dir("/dev/mmcblk0p1"), None);
    }

    #[test]
    fn trial_config_selects_slot_and_trial_cmdline() {
        let c = slot_config("gpu_mem=16\n[pi4]\narm_boost=1\n", Some("p3"), true);
        assert!(c.starts_with("gpu_mem=16"));
        assert!(c.ends_with("[all]\nos_prefix=p3/\ncmdline=cmdline.try.txt\n"));
        assert_eq!(configured_slot(&c), Some("p3"));
    }

    #[test]
    fn managed_block_is_replaced_not_stacked() {
        let user = "gpu_mem=16\nenable_uart=1";
        let a = slot_config(user, Some("p2"), false);
        let b = slot_config(&a, Some("p3"), false);
        assert_eq!(base_config(&b), user);
        assert_eq!(b.matches(MANAGED).count(), 1);
        assert_eq!(configured_slot(&b), Some("p3"));
        assert!(!b.contains("cmdline="));
        // Flat layout (no slot directory yet): only the trial command line.
        let flat = slot_config(user, None, true);
        assert_eq!(configured_slot(&flat), None);
        assert!(flat.ends_with("cmdline=cmdline.try.txt\n"));
        // tryboot.txt written by the previous release used the same marker.
        let old = "gpu_mem=16\n\n# Generated by pios-update: one-shot trial boot.\n[all]\ncmdline=cmdline.try.txt\n";
        assert_eq!(base_config(old), "gpu_mem=16");
    }

    #[test]
    fn adds_missing_root() {
        assert_eq!(root_of(&with_root("quiet", "/dev/mmcblk0p3")), Some("/dev/mmcblk0p3"));
    }

    #[test]
    fn manifest_round_trip_and_validation() {
        let sum = "ab".repeat(32);
        let text = format!("version 0.1.0 test\n{sum}  kernel7.img\n{sum}  rootfs.squashfs\n");
        let m = Manifest::parse(&text).unwrap();
        assert_eq!(m.version, "0.1.0 test");
        assert_eq!(m.sha256("kernel7.img"), Some(sum.as_str()));
        assert_eq!(Manifest::parse(&m.render()).unwrap(), m);
        assert!(Manifest::parse(&format!("{sum}  ../etc/passwd")).is_err());
        assert!(Manifest::parse("abc  kernel7.img").is_err());
    }

    #[test]
    fn classifies_bundle_members() {
        assert_eq!(classify("rootfs.squashfs"), Some(Member::Rootfs));
        assert_eq!(classify("kernel7.img"), Some(Member::Kernel));
        assert_eq!(classify("start_cd.elf"), Some(Member::Firmware));
        assert_eq!(classify("config.txt"), None);
    }
}
